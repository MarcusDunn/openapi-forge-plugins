#[derive(Debug)]
pub enum RenderError {
    /// Underlying primitive cannot be wrapped as a values4k Value.
    Unsupported(String),
}

impl fmt::Display for RenderError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            RenderError::Unsupported(msg) => write!(f, "{msg}"),
        }
    }
}

pub struct FileRender {
    pub path: String,
    pub source: String,
}

/// Render one file containing every `NamedType` in `types` that resolved to
/// `path`. Imports are computed from the cross-package references encountered
/// while rendering each body.
pub fn render_file(
    spec: &Ir,
    index: &FqcnIndex,
    variants: &VariantIndex,
    nest: &NestingTree,
    path: &str,
    types: &[&NamedType],
) -> Result<FileRender, RenderError> {
    // The file's Kotlin `package` declaration is the package of one of the
    // tree roots — i.e. the FQCN segments up to the last `.`. All roots in a
    // file should share a package (the build_nesting_tree contract); if they
    // disagree (misconfigured spec) the first root's package wins.
    let first_root = *nest
        .roots
        .first()
        .ok_or_else(|| RenderError::Unsupported(format!("no top-level types resolved for {path}")))?;
    let first_root_target = index
        .get(first_root)
        .expect("nesting tree roots come from the FqcnIndex");
    // Split the parsed package into (effective Kotlin package, phantom
    // wrapper-class segments). Phantom segments are PascalCase suffixes
    // that have no indexed schema — but the FQCN convention is
    // `ca.dialai.X.Y` = `class X { class Y { ... } }`, so we materialize an
    // empty `class X { ... }` wrapper rather than dropping the segment.
    let (package, auto_wrappers) =
        split_phantom_wrappers(&first_root_target.target.package, index);

    let mut ctx = FileCtx::new(&package, spec, index, variants);

    let mut bodies = String::new();
    for root_id in &nest.roots {
        let Some(named) = types.iter().find(|t| t.id.as_str() == *root_id).copied() else {
            continue;
        };
        let body = render_with_nested(&mut ctx, named, nest, types)?;
        if !bodies.is_empty() {
            bodies.push('\n');
        }
        bodies.push_str(&body);
    }

    // Wrap roots in any phantom outer classes — innermost first so we build
    // up `class Outer { class Inner { ...roots... } }` correctly.
    for wrapper in &auto_wrappers {
        let mut wrapped = String::new();
        // Phantom auto-wrappers exist purely to group children that share a
        // FQCN prefix without an explicit schema for the outer name. Match
        // the default `internal` visibility so they don't leak across
        // module boundaries by accident.
        let _ = writeln!(wrapped, "internal class {wrapper} {{");
        for line in bodies.lines() {
            if line.is_empty() {
                wrapped.push('\n');
            } else {
                let _ = writeln!(wrapped, "    {line}");
            }
        }
        let _ = writeln!(wrapped, "}}");
        bodies = wrapped;
    }

    let mut out = String::new();
    let _ = writeln!(out, "// Generated by generator-kotlin-types — do not edit.");
    if !ctx.use_serializers.is_empty() {
        // @file:UseSerializers wires the per-type serializers we emit at the
        // bottom of this file to every inline use of the underlying java.time
        // (or ByteArray) value. Saves a per-field @Serializable annotation at
        // every property site. Must precede the `package` line.
        let names: Vec<String> = ctx
            .use_serializers
            .iter()
            .map(|k| format!("{}::class", k.object_name()))
            .collect();
        let _ = writeln!(out, "@file:UseSerializers({})", names.join(", "));
        out.push('\n');
        ctx.imports.add("kotlinx.serialization.UseSerializers");
    }
    let _ = writeln!(out, "package {}", package);
    out.push('\n');
    let serializers = std::mem::take(&mut ctx.serializers_to_emit);
    let imports = ctx.imports.finish();
    if !imports.is_empty() {
        for line in imports {
            let _ = writeln!(out, "import {line}");
        }
        out.push('\n');
    }
    out.push_str(&bodies);
    for kind in &serializers {
        out.push('\n');
        out.push_str(kind.source());
    }

    Ok(FileRender {
        path: path.to_string(),
        source: out,
    })
}

// ---- file-scoped context for imports & inline-serializer tracking ----

struct FileCtx<'a> {
    package: &'a str,
    spec: &'a Ir,
    index: &'a FqcnIndex<'a>,
    variants: &'a VariantIndex<'a>,
    imports: ImportSet,
    /// Serializer objects that must be defined inline at the end of the file.
    /// A named wrapper (e.g. `CreatedAt` delegating to `OffsetDateTimeSerializer`)
    /// adds to this set without adding to `use_serializers`.
    serializers_to_emit: BTreeSet<SerKind>,
    /// Subset of `serializers_to_emit` that must also be wired up via
    /// `@file:UseSerializers(...)` so inline property uses of the underlying
    /// type (e.g. `val createdAt: OffsetDateTime`) round-trip without a per-field
    /// annotation. Only the inline path adds here; the wrapped path does not.
    use_serializers: BTreeSet<SerKind>,
}

impl<'a> FileCtx<'a> {
    fn new(
        package: &'a str,
        spec: &'a Ir,
        index: &'a FqcnIndex<'a>,
        variants: &'a VariantIndex<'a>,
    ) -> Self {
        Self {
            package,
            spec,
            index,
            variants,
            imports: ImportSet::default(),
            serializers_to_emit: BTreeSet::new(),
            use_serializers: BTreeSet::new(),
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum SerKind {
    /// `format: date-time` — RFC 3339 with offset preserved.
    OffsetDateTime,
    /// `format: instant` — a fixed UTC point in time (no offset info).
    Instant,
    LocalDate,
    LocalTime,
    Uuid,
    Base64Bytes,
}

impl SerKind {
    fn object_name(self) -> &'static str {
        match self {
            SerKind::OffsetDateTime => "OffsetDateTimeSerializer",
            SerKind::Instant => "InstantSerializer",
            SerKind::LocalDate => "LocalDateSerializer",
            SerKind::LocalTime => "LocalTimeSerializer",
            SerKind::Uuid => "UuidSerializer",
            SerKind::Base64Bytes => "Base64ByteArraySerializer",
        }
    }
    fn source(self) -> &'static str {
        match self {
            SerKind::OffsetDateTime => OFFSET_DATE_TIME_SERIALIZER,
            SerKind::Instant => INSTANT_SERIALIZER,
            SerKind::LocalDate => LOCAL_DATE_SERIALIZER,
            SerKind::LocalTime => LOCAL_TIME_SERIALIZER,
            SerKind::Uuid => UUID_SERIALIZER,
            SerKind::Base64Bytes => BASE64_BYTES_SERIALIZER,
        }
    }
}

#[derive(Default)]
struct ImportSet {
    items: BTreeSet<String>,
}

impl ImportSet {
    fn add(&mut self, fqcn: impl Into<String>) {
        self.items.insert(fqcn.into());
    }
    fn finish(self) -> Vec<String> {
        self.items.into_iter().collect()
    }
}

// ---- per-NamedType dispatch ----

/// Render `named` as a Kotlin source unit, plus recursively render every
/// FQCN-child (entries in `nest.children[named.id]`) and embed those rendered
/// bodies inside the parent's `{ ... }` block. Pure object/union/enum
/// parents can carry nested classes; value-wrappers / typealiases / arrays
/// cannot, and surface a `RenderError::Unsupported` when nesting is asked of
/// them.
fn render_with_nested(
    ctx: &mut FileCtx,
    named: &NamedType,
    nest: &NestingTree,
    types: &[&NamedType],
) -> Result<String, RenderError> {
    // Render children first so they can populate `ctx.imports` /
    // `ctx.serializers_to_emit` before the parent writes its body.
    let mut child_bodies: Vec<String> = Vec::new();
    if let Some(children) = nest.children.get(named.id.as_str()) {
        for child_id in children {
            let Some(child) = types.iter().find(|t| t.id.as_str() == *child_id).copied() else {
                continue;
            };
            let body = render_with_nested(ctx, child, nest, types)?;
            child_bodies.push(body);
        }
    }
    render_named(ctx, named, &child_bodies)
}

fn render_named(
    ctx: &mut FileCtx,
    named: &NamedType,
    fqcn_children: &[String],
) -> Result<String, RenderError> {
    let resolved = ctx
        .index
        .get(named.id.as_str())
        .expect("render_named called on un-indexed type");
    let class_name = resolved.target.class_name.clone();
    let vis = resolved.visibility.modifier();

    match &named.definition {
        TypeDef::Primitive(p) => {
            reject_nesting(&class_name, "primitive value wrapper", fqcn_children)?;
            render_value_object(ctx, &class_name, vis, named, p)
        }
        TypeDef::Object(o) => render_object(ctx, &class_name, vis, named, o, fqcn_children),
        TypeDef::EnumString(e) => render_enum_string(ctx, &class_name, vis, e, fqcn_children),
        TypeDef::EnumInt(e) => {
            reject_nesting(&class_name, "integer enum", fqcn_children)?;
            render_enum_int(ctx, &class_name, vis, e)
        }
        TypeDef::Union(u) => render_union(ctx, &class_name, vis, named, u, fqcn_children),
        TypeDef::Array(_) => {
            reject_nesting(&class_name, "array typealias", fqcn_children)?;
            render_array_alias(ctx, &class_name, vis, named)
        }
        TypeDef::Null => Err(RenderError::Unsupported(
            "the null type cannot be rendered as a Kotlin class".into(),
        )),
    }
}

fn reject_nesting(
    class_name: &str,
    shape: &str,
    fqcn_children: &[String],
) -> Result<(), RenderError> {
    if fqcn_children.is_empty() {
        return Ok(());
    }
    Err(RenderError::Unsupported(format!(
        "'{class_name}' is a {shape}; Kotlin doesn't allow nested classes inside it. \
         Move the FQCN children to a sibling file, or change '{class_name}' to an object/sealed/enum"
    )))
}

// ---- value object (values4k wrapper) ----

fn render_value_object(
    ctx: &mut FileCtx,
    class_name: &str,
    vis: &str,
    named: &NamedType,
    p: &forge_plugin_sdk::ir::PrimitiveType,
) -> Result<String, RenderError> {
    // Special-format string primitives don't fit the values4k *Value model.
    // Wrap the matching JVM type with our inlined per-format KSerializer.
    if matches!(p.kind, PrimitiveKind::String) {
        match p.constraints.format_extension.as_deref() {
            Some("date-time") => {
                return Ok(render_special_wrapper(ctx, class_name, vis, SerKind::OffsetDateTime));
            }
            Some("instant") => {
                return Ok(render_special_wrapper(ctx, class_name, vis, SerKind::Instant));
            }
            Some("date") => {
                return Ok(render_special_wrapper(ctx, class_name, vis, SerKind::LocalDate));
            }
            Some("time") => {
                return Ok(render_special_wrapper(ctx, class_name, vis, SerKind::LocalTime));
            }
            Some("uuid") => {
                return Ok(render_special_wrapper(ctx, class_name, vis, SerKind::Uuid));
            }
            Some("byte") => {
                return Ok(render_byte_wrapper(ctx, class_name, vis));
            }
            _ => {}
        }
    }

    let plan = ValuePlan::for_primitive(ctx.spec, p)?;
    ctx.imports.add("kotlinx.serialization.KSerializer");
    ctx.imports.add("kotlinx.serialization.Serializable");
    ctx.imports
        .add("kotlinx.serialization.descriptors.PrimitiveKind");
    ctx.imports
        .add("kotlinx.serialization.descriptors.PrimitiveSerialDescriptor");
    ctx.imports.add("kotlinx.serialization.encoding.Decoder");
    ctx.imports.add("kotlinx.serialization.encoding.Encoder");
    ctx.imports.add(format!("dev.forkhandles.values.{}", plan.base_class));
    ctx.imports
        .add(format!("dev.forkhandles.values.{}", plan.factory_class));
    for ext in &plan.validation_extensions {
        ctx.imports.add(format!("dev.forkhandles.values.{}", ext));
    }

    let factory_arg = plan.validation_expr();
    let factory_line = match factory_arg {
        Some(expr) => format!(
            "    companion object : {factory}<{cls}>(::{cls}, {expr})",
            factory = plan.factory_class,
            cls = class_name,
            expr = expr
        ),
        None => format!(
            "    companion object : {factory}<{cls}>(::{cls})",
            factory = plan.factory_class,
            cls = class_name
        ),
    };

    let underlying_kt = plan.underlying_kt;
    let descriptor_kind = plan.descriptor_kind;
    let encode_call = plan.encode_call;
    let decode_call = plan.decode_call;

    let mut out = String::new();
    if let Some(doc) = doc_block(named) {
        out.push_str(&doc);
    }
    let _ = writeln!(
        out,
        "@Serializable(with = {class_name}.Serializer::class)\n\
         {vis}data class {class_name} private constructor(val value: {underlying_kt}) : {base}(value) {{",
        base = plan.base_class
    );
    let _ = writeln!(out, "{factory_line}");
    out.push('\n');
    let _ = writeln!(
        out,
        "    internal object Serializer : KSerializer<{class_name}> {{\n\
            \x20       override val descriptor = PrimitiveSerialDescriptor(\"{class_name}\", PrimitiveKind.{descriptor_kind})\n\
            \x20       override fun serialize(encoder: Encoder, value: {class_name}) = encoder.{encode_call}(value.value)\n\
            \x20       override fun deserialize(decoder: Decoder): {class_name} = {class_name}.of(decoder.{decode_call}())\n\
            \x20   }}"
    );
    out.push_str("}\n");
    Ok(out)
}

fn render_special_wrapper(
    ctx: &mut FileCtx,
    class_name: &str,
    vis: &str,
    kind: SerKind,
) -> String {
    ctx.imports.add("kotlinx.serialization.KSerializer");
    ctx.imports.add("kotlinx.serialization.Serializable");
    ctx.imports
        .add("kotlinx.serialization.descriptors.PrimitiveKind");
    ctx.imports
        .add("kotlinx.serialization.descriptors.PrimitiveSerialDescriptor");
    ctx.imports.add("kotlinx.serialization.encoding.Decoder");
    ctx.imports.add("kotlinx.serialization.encoding.Encoder");
    let underlying = match kind {
        SerKind::OffsetDateTime => {
            ctx.imports.add("java.time.OffsetDateTime");
            "OffsetDateTime"
        }
        SerKind::Instant => {
            ctx.imports.add("java.time.Instant");
            "Instant"
        }
        SerKind::LocalDate => {
            ctx.imports.add("java.time.LocalDate");
            "LocalDate"
        }
        SerKind::LocalTime => {
            ctx.imports.add("java.time.LocalTime");
            "LocalTime"
        }
        SerKind::Uuid => {
            ctx.imports.add("java.util.UUID");
            "UUID"
        }
        SerKind::Base64Bytes => unreachable!("byte → render_byte_wrapper"),
    };
    // The wrapped path only needs the serializer object itself (not the
    // @file:UseSerializers directive — the wrapper's own KSerializer takes
    // over for `class_name`, and the underlying type only appears inside the
    // wrapper's body, never as a free-standing inline property).
    ctx.serializers_to_emit.insert(kind);
    let helper = kind.object_name();

    let mut out = String::new();
    let _ = writeln!(
        out,
        "@Serializable(with = {class_name}.Serializer::class)\n\
         {vis}data class {class_name}(val value: {underlying}) {{\n\
            \x20   internal object Serializer : KSerializer<{class_name}> by {helper}.map({class_name}::value, ::{class_name})\n\
         }}"
    );
    out
}

/// Wrap `type: string, format: byte` (Base64-encoded bytes) as a `ByteArray`
/// data class. values4k has no `ByteArrayValue`, so this doesn't inherit a
/// `*Value` base — but it keeps the rest of the pattern (private constructor,
/// `of(...)` factory, custom `KSerializer` that round-trips through a JSON
/// Base64 string).
fn render_byte_wrapper(ctx: &mut FileCtx, class_name: &str, vis: &str) -> String {
    ctx.imports.add("kotlinx.serialization.KSerializer");
    ctx.imports.add("kotlinx.serialization.Serializable");
    ctx.imports
        .add("kotlinx.serialization.descriptors.PrimitiveKind");
    ctx.imports
        .add("kotlinx.serialization.descriptors.PrimitiveSerialDescriptor");
    ctx.imports.add("kotlinx.serialization.encoding.Decoder");
    ctx.imports.add("kotlinx.serialization.encoding.Encoder");
    let mut out = String::new();
    let _ = writeln!(
        out,
        "@Serializable(with = {class_name}.Serializer::class)\n\
         {vis}data class {class_name} private constructor(val value: ByteArray) {{\n\
            \x20   companion object {{ fun of(value: ByteArray): {class_name} = {class_name}(value) }}\n\
         \n\
            \x20   internal object Serializer : KSerializer<{class_name}> {{\n\
            \x20       override val descriptor = PrimitiveSerialDescriptor(\"{class_name}\", PrimitiveKind.STRING)\n\
            \x20       override fun serialize(encoder: Encoder, value: {class_name}) =\n\
            \x20           encoder.encodeString(java.util.Base64.getEncoder().encodeToString(value.value))\n\
            \x20       override fun deserialize(decoder: Decoder): {class_name} =\n\
            \x20           {class_name}(java.util.Base64.getDecoder().decode(decoder.decodeString()))\n\
            \x20   }}\n\
         }}"
    );
    out
}

